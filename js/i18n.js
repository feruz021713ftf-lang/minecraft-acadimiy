window.appSourceText = value => {
  let result = value;
  const entries = [...translations.entries()]
    .map(([source, values]) => [source, values[language]])
    .filter(([source, local]) => local && local !== source)
    .sort((a, b) => b[1].length - a[1].length);
  for (const [source, local] of entries) {
    result = result.replace(new RegExp(local.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'giu'), source);
  }
  return result;
};

function translateTextNode(node) {
  const current = node.nodeValue;
  const record = textRecords.get(node);
  const source = record && current === record.translated ? record.source : current;
  const clean = source.trim().replace(/\s+/g, ' ');
  const result = translatedNode(clean, node);
  if (result == null) {
    if (record) textRecords.set(node, { source, translated: source });
    return;
  }

  const leading = source.match(/^\s*/)?.[0] || '';
  const trailing = source.match(/\s*$/)?.[0] || '';
  const output = leading + result + trailing;
  textRecords.set(node, { source, translated: output });
  if (current !== output) node.nodeValue = output;
}

function translateAttributes(root) {
  const elements = [];
  if (root.nodeType === Node.ELEMENT_NODE) elements.push(root);
  if (root.querySelectorAll) elements.push(...root.querySelectorAll('[aria-label], [title], [placeholder], [alt], meta[name="description"]'));

  for (const element of elements) {
    if (element.closest('[data-language-control]')) continue;
    const attributes = element.matches('meta[name="description"]') ? ['content'] : ['aria-label', 'title', 'placeholder', 'alt'];
    let records = attributeRecords.get(element);
    if (!records) {
      records = new Map();
      attributeRecords.set(element, records);
    }

    for (const name of attributes) {
      const current = element.getAttribute(name);
      if (current == null) continue;
      const record = records.get(name);
      const source = record && current === record.translated ? record.source : current;
      const result = translated(source.trim().replace(/\s+/g, ' '));
      if (!result) continue;
      records.set(name, { source, translated: result });
      if (current !== result) element.setAttribute(name, result);
    }
  }
}

function translateSubtree(root = document.documentElement) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest('script, style, [data-language-control]')) continue;
    translateTextNode(node);
  }
  translateAttributes(root);
  const title = document.querySelector('title');
  if (title) {
    const source = title.textContent;
    const record = title.dataset.i18nSource;
    const original = record && source === title.dataset.i18nTranslated ? record : source;
    const result = titles.get(original)?.[language];
    if (result) {
      title.dataset.i18nSource = original;
      title.dataset.i18nTranslated = result;
      title.textContent = result;
    }
  }
}

