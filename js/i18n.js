function translated(source) {
  const exact = translations.get(source)?.[language];
  if (exact) return exact;

  let match = source.match(/^(\d+) of (\d+) unlocked\.$/);
  if (match) return language === 'uz'
    ? `${match[1]} / ${match[2]} ta yutuq ochildi.`
    : `Открыто достижений: ${match[1]} из ${match[2]}.`;

  match = source.match(/^Question (\d+) of (\d+)$/);
  if (match) return language === 'uz'
    ? `${match[2]} tadan ${match[1]}-savol`
    : `Вопрос ${match[1]} из ${match[2]}`;

  match = source.match(/^(\d+) XP to (.+)$/);
  if (match) return language === 'uz'
    ? `${match[2]} darajasigacha ${match[1]} XP`
    : `${match[1]} XP до ранга «${translations.get(match[2])?.[language] || match[2]}»`;

  match = source.match(/^(.+) · Level (\d+)$/);
  if (match) return language === 'uz'
    ? `${translations.get(match[1])?.uz || match[1]} · ${match[2]}-daraja`
    : `Ранг «${translations.get(match[1])?.ru || match[1]}» · ${match[2]} уровень`;

  match = source.match(/^(.+) · (\d+) min · \+(\d+) XP$/);
  if (match) return language === 'uz'
    ? `${translations.get(match[1])?.uz || match[1]} · ${match[2]} daq. · +${match[3]} XP`
    : `${translations.get(match[1])?.ru || match[1]} · ${match[2]} мин. · +${match[3]} XP`;

  match = source.match(/^Ingredients: (.+)$/);
  if (match) {
    const items = match[1].split(', ').map(item => translations.get(item)?.[language] || item);
    return `${language === 'uz' ? 'Masalliqlar' : 'Ингредиенты'}: ${items.join(', ')}`;
  }

  match = source.match(/^(.+) ×(\d+)$/);
  if (match && translations.has(match[1])) {
    return `${translations.get(match[1])[language]} ×${match[2]}`;
  }

  match = source.match(/^Checkpoint (\d+) reached!$/);
  if (match) return language === 'uz'
    ? `${match[1]}-nazorat nuqtasiga yetdingiz!`
    : `Контрольная точка ${match[1]} достигнута!`;

  match = source.match(/^🏁 Completed in ([\d.]+)s!$/);
  if (match) return language === 'uz'
    ? `🏁 ${match[1]} soniyada yakunlandi!`
    : `🏁 Завершено за ${match[1]} с!`;

  match = source.match(/^(.+) · (.+)$/);
  if (match) {
    const first = translations.get(match[1])?.[language];
    const second = translations.get(match[2])?.[language];
    if (first || second) {
      return `${first || match[1]} · ${second || match[2]}`;
    }
  }

  match = source.match(/^(\d+)([mhd]) ago$/);
  if (match) {
    const units = language === 'uz'
      ? { m: ' daqiqa oldin', h: ' soat oldin', d: ' kun oldin' }
      : { m: ' мин. назад', h: ' ч. назад', d: ' дн. назад' };
    return match[1] + units[match[2]];
  }

  match = source.match(/^(\d+)\/(\d+) lessons$/);
  if (match) return language === 'uz'
    ? `${match[1]}/${match[2]} ta dars`
    : `${match[1]}/${match[2]} уроков`;

  match = source.match(/^Score: (\d+)\/(\d+)\.?$/);
  if (match) return language === 'uz'
    ? `Hisob: ${match[1]}/${match[2]}.`
    : `Счет: ${match[1]}/${match[2]}.`;

  match = source.match(/^Quiz complete! Score: (\d+)\/(\d+)\. \+(\d+) XP\.$/);
  if (match) return language === 'uz'
    ? `Test tugadi! Hisob: ${match[1]}/${match[2]}. +${match[3]} XP.`
    : `Тест завершен! Счет: ${match[1]}/${match[2]}. +${match[3]} XP.`;

  match = source.match(/^Score: (\d+)\/(\d+)\. \+(\d+) XP\.$/);
  if (match) return language === 'uz'
    ? `Hisob: ${match[1]}/${match[2]}. +${match[3]} XP.`
    : `Счет: ${match[1]}/${match[2]}. +${match[3]} XP.`;

  match = source.match(/^Crafted (.+)! \+(\d+) XP$/);
  if (match) return language === 'uz'
    ? `${translations.get(match[1])?.uz || match[1]} yasaldi! +${match[2]} XP`
    : `Создано: ${translations.get(match[1])?.ru || match[1]}! +${match[2]} XP`;

  match = source.match(/^Recipe matched: (.+)$/);
  if (match) return language === 'uz'
    ? `Retsept mos keldi: ${translations.get(match[1])?.uz || match[1]}`
    : `Рецепт найден: ${translations.get(match[1])?.ru || match[1]}`;

  match = source.match(/^Selected: (.+)$/);
  if (match) return language === 'uz'
    ? `Tanlandi: ${translations.get(match[1])?.uz || match[1]}`
    : `Выбрано: ${translations.get(match[1])?.ru || match[1]}`;

  match = source.match(/^❌ (?:Incorrect\. )?Correct(?: answer)?: (.+)$/);
  if (match) return language === 'uz'
    ? `❌ To'g'ri javob: ${translations.get(match[1])?.uz || match[1]}`
    : `❌ Правильный ответ: ${translations.get(match[1])?.ru || match[1]}`;

  match = source.match(/^\+(\d+) XP · Lesson: (.+)$/);
  if (match) return language === 'uz'
    ? `+${match[1]} XP · Dars: ${match[2]}`
    : `+${match[1]} XP · Урок: ${match[2]}`;

  match = source.match(/^\+(\d+) XP · Achievement: (.+)$/);
  if (match) return language === 'uz'
    ? `+${match[1]} XP · Yutuq: ${translations.get(match[2])?.uz || match[2]}`
    : `+${match[1]} XP · Достижение: ${translations.get(match[2])?.ru || match[2]}`;

  match = source.match(/^Rank up → (.+)$/);
  if (match) return language === 'uz'
    ? `Daraja oshdi → ${translations.get(match[1])?.uz || match[1]}`
    : `Новый ранг → ${translations.get(match[1])?.ru || match[1]}`;

  match = source.match(/^([A-Za-z].+) ✅$/);
  if (match) {
    const translatedTitle = translations.get(match[1])?.[language];
    if (translatedTitle) return `${translatedTitle} ✅`;
  }

  match = source.match(/^Cell (\d+)$/);
  if (match) return language === 'uz' ? `${match[1]}-katak` : `Ячейка ${match[1]}`;
  match = source.match(/^Hotbar slot (\d+)$/);
  if (match) return language === 'uz' ? `Tezkor panel katagi ${match[1]}` : `Ячейка панели быстрого доступа ${match[1]}`;

  return titles.get(source)?.[language] || null;
}

function translatedNode(source, node) {
  const heading = node.parentElement?.closest('.hero h1');
  if (!heading) return translated(source);

  if (node.parentElement.matches('.text-emerald') && source === 'Beginner') {
    return language === 'uz' ? ' ' : 'новичка';
  }
  if (node.parentElement.matches('.text-gold') && source === 'Legend') {
    return language === 'uz' ? 'Afsonagacha' : 'легенды';
  }
  if (source === 'From') return language === 'uz' ? 'Boshlovchidan' : 'От';
  if (source === 'to') return language === 'uz' ? ' ' : 'до';
  return translated(source);
}

